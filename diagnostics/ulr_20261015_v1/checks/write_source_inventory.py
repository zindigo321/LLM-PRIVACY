"""ULR-20261015-v1: write SOURCE_INVENTORY.md, the provenance of every vendored file (read-only on sources).

``python -B checks/write_source_inventory.py``. Every file under ``vendor/uoa_20261014_v1/`` must be byte-identical
to the same path in the frozen UOA package and equal to its entry in the UOA manifest (``c8b30ab0...46ed``). Those
UOA files exist only locally (UOA is unpublished); the deeper UCX / Uformer / UPP copies are recorded with their
git-blob status at the verified main. Refuses on any mismatch.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parents[1]
UOA_PKG = Path("D:/projects-cd/cg-fedllm-uoa/diagnostics/uoa_20261014_v1")
MAIN = "0238e3b774e0f97f171bc5cbc53f1ec06aa49c7e"
GIT_PATH = {
    "vendor/uid_20261012_v2/": "diagnostics/uid_20261012_v2/",
    "vendor/uid_20261012_v2_r1/": "diagnostics/uid_20261012_v2_r1/",
}


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def main() -> int:
    m = json.loads((UOA_PKG / "manifest_uoa.json").read_text("utf-8"))
    idx = {e["path"]: e["sha256"] for e in m["files"]}
    rows, bad = [], []
    base = PKG / "vendor" / "uoa_20261014_v1"
    for p in sorted(base.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(base).as_posix()
        s_src, s_dst = sha((UOA_PKG / rel).read_bytes()), sha(p.read_bytes())
        git_rel = next((g + rel[len(v) :] for v, g in GIT_PATH.items() if rel.startswith(v)), None)
        blob = None
        if git_rel:
            r = subprocess.run(
                ["git", "-C", str(PKG.parents[1]), "show", f"{MAIN}:{git_rel}"], capture_output=True
            )
            blob = sha(r.stdout) if r.returncode == 0 else None
        status = "tracked at main" if blob else "local only (absent from origin/main)"
        if not (s_src == s_dst == idx.get(rel) and (blob is None or blob == s_dst)):
            bad.append(rel)
        rows.append((rel, status, s_dst))
    if bad:
        raise SystemExit(f"vendored files differ from their sources or the UOA manifest: {bad}")
    lines = [
        "# ULR-20261015-v1 source inventory (vendored dependencies)",
        "",
        "Generated by `checks/write_source_inventory.py` before the freeze.",
        "",
        "- Every file below is a byte copy of the same path in the frozen UOA package `D:/projects-cd/cg-fedllm-uoa/diagnostics/uoa_20261014_v1/`.",
        "- Each equals its entry in the UOA manifest `c8b30ab08abcdae5a3564ece49e77c64d305856b8d0041b1b7da8eda135446ed`.",
        "- The copies are never edited; ruff checks exclude `vendor/`.",
        "- *Local only* means the file is absent from `origin/main` `0238e3b`. *Tracked at main* means it also equals its git blob there.",
        "",
        "| Vendored path (under `vendor/uoa_20261014_v1/`) | Git status | SHA-256 |",
        "|---|---|---|",
        *[f"| `{rel}` | {status} | `{s}` |" for rel, status, s in rows],
        "",
        "External run inputs (not copied; verified by SHA-256 at every read) are listed in `protocol.md` section 3 and in `manifest_ulr.json` (`external_bound_files`).",
        "",
    ]
    (PKG / "SOURCE_INVENTORY.md").open("x", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"{len(rows)} vendored files, all byte-identical and in the UOA manifest")
    return 0


if __name__ == "__main__":
    sys.exit(main())
